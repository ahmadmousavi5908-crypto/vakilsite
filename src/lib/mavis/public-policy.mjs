export function isPublicAssistantEnabled(env = process.env) {
  return env.MAVIS_PUBLIC_ENABLED === "true";
}

export function getPublicAssistantConfig(env = process.env) {
  return Object.freeze({
    enabled: isPublicAssistantEnabled(env),
    maxOutputTokens: 700,
    provider: env.MAVIS_PROVIDER || "mock",
  });
}
